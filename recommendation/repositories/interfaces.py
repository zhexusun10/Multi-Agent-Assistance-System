from typing import Protocol
from recommendation.contracts.requirements import Criterion
from recommendation.contracts.evidence import Evidence
from ..models.listing_summary import ListingSummary


class ListingRepository(Protocol):
    mode: str

    def retrieve(self) -> list[ListingSummary]: ...
    def lookup(self, ids: list[str]) -> list[ListingSummary]: ...
    def health(self) -> dict: ...
    def close(self) -> None: ...


class GeographicRepository(Protocol):
    def evidence(
        self, listings: list[ListingSummary], criteria: list[Criterion]
    ) -> list[Evidence]: ...
    def health(self) -> dict: ...
    def close(self) -> None: ...
